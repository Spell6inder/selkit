type msg struct {
	id, plural string
	refs       []string
}

// extract collects strings from i18n.T / Tf / Mark (one string) and N / Nf (singular and plural) calls across the whole module.
func extract(t *testing.T) []*msg {
	root := filepath.Join("..", "..")
	byID := map[string]*msg{}
	var order []*msg
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (d.Name() == "var" || strings.HasPrefix(d.Name(), ".")) && path != root {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			pkg, ok := sel.X.(*ast.Ident)
			if !ok || pkg.Name != "i18n" {
				return true
			}
			lit := func(i int) string {
				if i >= len(call.Args) {
					return ""
				}
				s, ok := constString(call.Args[i])
				if !ok {
					if sel.Sel.Name == "T" {
						return "" // T(variable): the string is marked via i18n.Mark where it is defined
					}
					t.Errorf("%s: i18n.%s with a non-literal string - it will not be in the catalog", fset.Position(call.Pos()), sel.Sel.Name)
				}
				return s
			}
			var id, plural string
			switch sel.Sel.Name {
			case "T", "Tf", "Mark":
				id = lit(0)
			case "N", "Nf":
				id, plural = lit(0), lit(1)
			default:
				return true
			}
			if id == "" {
				return true
			}
			pos := fset.Position(call.Pos())
			rel, _ := filepath.Rel(root, pos.Filename)
			ref := fmt.Sprintf("%s:%d", filepath.ToSlash(rel), pos.Line)
			if m, ok := byID[id]; ok {
				m.refs = append(m.refs, ref)
			} else {
				m := &msg{id: id, plural: plural, refs: []string{ref}}
				byID[id] = m
				order = append(order, m)
			}
			return true
		})
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return order
}

func quote(s string) string {
	s = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\t", `\t`).Replace(s)
	return `"` + s + `"`
}

func pot(msgs []*msg) string {
	var b strings.Builder
	b.WriteString("# Selkit translation template. Generated by: SELKIT_UPDATE_POT=1 go test ./internal/i18n\n")
	b.WriteString("msgid \"\"\nmsgstr \"\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Content-Transfer-Encoding: 8bit\\n\"\n")
	for _, m := range msgs {
		b.WriteString("\n")
		for _, r := range m.refs {
			b.WriteString("#: " + r + "\n")
		}
		if strings.Contains(m.id, "%") {
			b.WriteString("#, c-format\n")
		}
		b.WriteString("msgid " + quote(m.id) + "\n")
		if m.plural != "" {
			b.WriteString("msgid_plural " + quote(m.plural) + "\nmsgstr[0] \"\"\nmsgstr[1] \"\"\n")
		} else {
			b.WriteString("msgstr \"\"\n")
		}
	}
	return b.String()
}

// TestTemplate: resources/locales/selkit.pot must match the strings in the code.
func TestTemplate(t *testing.T) {
	want := pot(extract(t))
	path := filepath.Join("..", "..", "resources", "locales", "selkit.pot")
	if os.Getenv("SELKIT_UPDATE_POT") != "" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, _ := os.ReadFile(path)
	if strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Errorf("%s is out of date - update it: SELKIT_UPDATE_POT=1 go test ./internal/i18n", path)
	}
}

var verb = regexp.MustCompile(`%[-+# 0]*[0-9]*(?:\.[0-9]+)?[a-zA-Z%]`)

func verbs(s string) []string {
	v := verb.FindAllString(s, -1)
	slices.Sort(v)
	return v
}

// TestTranslations: every embedded translation covers all strings, has no extras and uses the same % verbs.
func TestTranslations(t *testing.T) {
	msgs := extract(t)
	files, _ := filepath.Glob(filepath.Join("..", "..", "resources", "locales", "*.po"))
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		entries, err := parseEntries(string(data))
		if err != nil {
			t.Fatalf("%s: %v", file, err)
		}
		c, err := parsePO(string(data))
		if err != nil {
			t.Fatalf("%s: %v", file, err)
		}
		have := map[string]bool{}
		for _, e := range entries {
			if e.id != "" {
				have[e.id] = true
			}
		}
		for _, m := range msgs {
			tr, ok := c.msgs[m.id]
			if !ok {
				t.Errorf("%s: no translation for %q", file, m.id)
				continue
			}
			for i, s := range tr {
				src := m.id
				if i > 0 && m.plural != "" {
					src = m.plural
				}
				// %d may be omitted in the singular form ("one line"), so compare only plural forms against the plural.
				if m.plural != "" && i == 0 {
					continue
				}
				if !slices.Equal(verbs(src), verbs(s)) {
					t.Errorf("%s: %q → %q: verbs %v, want %v", file, m.id, s, verbs(s), verbs(src))
				}
			}
			delete(have, m.id)
		}
		for id := range have {
			t.Errorf("%s: translation for a string no longer in the code: %q", file, id)
		}
	}
}

// constString returns a string literal or literals concatenated with + (long strings are split that way).
func constString(e ast.Expr) (string, bool) {
	switch e := e.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			return "", false
		}
		s, err := strconv.Unquote(e.Value)
		return s, err == nil
	case *ast.BinaryExpr:
		if e.Op != token.ADD {
			return "", false
		}
		a, ok1 := constString(e.X)
		b, ok2 := constString(e.Y)
		return a + b, ok1 && ok2
	case *ast.ParenExpr:
		return constString(e.X)
	}
	return "", false
}
